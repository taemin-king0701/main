    st.write("---")
    
    st.markdown(f"## 🎉 {selected_mbti} 유형, 당신은 어떤 사람인가요? 🎉")
    st.success(f"### {data['title']}\n\n**{data['traits']}**")
    
    st.write("")
    
    st.markdown(f"## 🎯 {selected_mbti}에게 찰떡궁합인 직업 BEST 3 🎯")
    colors = [st.info, st.warning, st.error] 
    
    for i, job in enumerate(data['jobs']):
        color_box = colors[i % len(colors)]
        color_box(f"#### {i+1}. {job['name']}\n\n💡 **추천 이유:** {job['reason']}")
        
    st.write("---")
    st.info("🌈 **선생님의 한마디:** MBTI는 힌트일 뿐, 여러분의 잠재력은 우주만큼 무궁무진합니다! 🚀✨")
